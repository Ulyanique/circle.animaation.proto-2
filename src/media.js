// Что показывают «окна»: свои видео вместо кадров-заглушек.
//
// Файлы кладутся в public/media/. Одна строка — одно окно: w01 … w11, по порядку появления в ролике (карта окон и
// таблица с кадрами — в README, раздел «Свои фото и видео в окнах»). Окно без строки показывает прежнюю заглушку.
//
//   src      файл: фото (jpg, png, webp, avif) или видео (mp4, webm); видео идёт без звука
//   x, y     какую часть кадра показать, 0…1: x: 0 — левый край, 0.5 — середина, 1 — правый; y: 0 — верх, 1 — низ
//   zoom     увеличение, от 1 (1 — кадр ровно закрывает окно, больше — крупнее)
//   rotate   поворот кадра по часовой стрелке, в градусах; 'level' — выровнять по горизонту экрана (часть окон наклонена)
//   to       { x, y, zoom, rotate } — к чему плавно прийти, пока окно на экране: медленный наезд или панорама
//   fixed    true — кадр закреплён на экране и занимает его целиком, а окно — прорезь, сквозь которую он виден
//            (как background-attachment: fixed в CSS); false — кадр «наклеен» на окно и летит вместе с ним.
//            По умолчанию false, а для w04 — true: это окно во весь экран
//   start    видео: с какой секунды начать;  rate — скорость (1 — обычная);  loop: false — не повторять
//   sharpen  подчеркнуть резкость мягкого исходника, 0…1 (по умолчанию 0 — кадр показывается как есть)
//
// Как подгонять: запустите npm run dev и нажмите E на странице — файл можно перетащить прямо на окно, кадр двигается
// мышью, а кнопка «Сохранить» сама пишет строки сюда. Или руками: остановите ролик на нужном окне (пробел; стрелки —
// на секунду, с Shift — на кадр) и меняйте числа здесь — положение кадра меняется на экране сразу.
// Адрес с ?card покажет во всех окнах разметку 16:9 вместо картинок: видно, какую часть кадра берёт каждое окно.
//
// Окна Cirkul 2024 (нарезки из папки Google Drive `arena.ai/circle/video/`). Окно w07 (0,5 с, кадр 522) не занято:
// плейсхолдеров должно быть десять. Имена файлов — локальные (ASCII); соответствия:
//
//   w01  media/badges.mp4         ← «00.07 Бэйджи.mp4»
//   w02  media/shulgan.mp4        ← «01.25-01.28 Шульган.mp4»
