// Что показывают «окна»: нарезки Cirkul 2024 из public/media/ (папка cuts/ на Google Диске).
//
// Файлы кладутся в public/media/. Одна строка — одно окно: w01 … w11, по порядку появления в ролике (карта окон и
// таблица с кадрами — в README, раздел «Свои фото и видео в окнах»). Окно без строки остаётся пустым стеклом:
// стопкадров-заглушек в проекте нет.
//
//   src      файл: фото (jpg, png, webp, avif) или видео (mp4, webm); видео идёт без звука
//   x, y     какую часть кадра показать, 0…1: x: 0 — левый край, 0.5 — середина, 1 — правый; y: 0 — верх, 1 — низ
//   zoom     увеличение, от 1 (1 — кадр ровно закрывает окно, больше — крупнее)
//   rotate   поворот кадра по часовой стрелке, в градусах; 'level' — выровнять по горизонту экрана (часть окон наклонена)
//   to       { x, y, zoom, rotate } — к чему плавно прийти, пока окно на экране: медленный наезд или панорама
//   fixed    true — кадр закреплён на экране и занимает его целиком, а окно — прорезь, сквозь которую он виден
//            (как background-attachment: fixed в CSS); false — кадр «наклеен» на окно и летит вместе с ним.
//            По умолчанию false, а для w04 — true: это окно во весь экран
//   start    видео: с какой секунды начать;  rate — скорость (1 — обычная);  loop: false — не повторять
//   sharpen  подчеркнуть резкость мягкого исходника, 0…1 (по умолчанию 0 — кадр показывается как есть)
//
// Как подгонять: запустите npm run dev и нажмите E на странице — файл можно перетащить прямо на окно, кадр двигается
// мышью, а кнопка «Сохранить» сама пишет строки сюда. Или руками: остановите ролик на нужном окне (пробел; стрелки —
// на секунду, с Shift — на кадр) и меняйте числа здесь — положение кадра меняется на экране сразу.
// Адрес с ?card покажет во всех окнах разметку 16:9 вместо картинок: видно, какую часть кадра берёт каждое окно.
//
// Окна Cirkul 2024 (нарезки из папки `cuts/`, теперь `public/media/`). Все одиннадцать окон показывают только эти
// нарезки — заглушек-стопкадров в ролике не осталось ни одного. Имена файлов — локальные (ASCII); соответствия:
//
//   w01  media/badges.mp4         ← «00.07 Бэйджи.mp4»              (0–1,15 с)
//   w02  media/shulgan.mp4        ← «01.25-01.28 Шульган.mp4»      (0–1,8 с)
//   w03  media/sobol-anisimov.mp4 ← «01.25 СобольАнисимов.mp4»     (0–2,4 с)
//   w04  media/hall.mp4           ← «03.36 Общий план зала.mp4»    (окно во весь экран, fixed)
//   w05  media/tikhonova.mp4      ← «03.34 Тихонова.mp4»           (0–2,6 с)
//   w06  media/zikeev.mp4         ← «03.52 Зикеев.mp4»             (0,4–1,9 с: лицо награждённого, крупно)
//   w07  media/zikeev.mp4         ← та же нарезка, дальше: 2,1–2,55 с — общий план сцены
//   w08  media/borovskaya.mp4     ← «04.51 Боровская.mp4»
//   w09  media/yushkevichus.mp4   ← «04.59 Юшкевичус.mp4»
//   w10  media/photozone.mp4      ← «05.41 фотозона.mp4»           (14,4 с — в окне зацикливается)
//   w11  media/winners.mp4        ← «05.44 все победители.mp4»     (финал, перед вспышкой)
//
// Нарезок десять, а окон одиннадцать, поэтому одно окно берёт вторую часть той же нарезки: w07 (0,5 с) идёт сразу
// за w06, и «Зикеев» продолжается в нём с 2,1 с — общим планом сцены (он горизонтальный, а окно w07 — 1,87 : 1).
// Две строки на один файл — это два независимых <video> на один и тот же MP4: браузер берёт файл из кэша, лишней
// загрузки нет, а в окнах идут разные моменты нарезки. Так заняты все окна, и ни одна нарезка не остаётся в стороне.
//
// Пока какого-то файла нет на диске, окно остаётся пустым стеклом и пишет предупреждение в консоль; нарезка, которая
// придёт позже, подхватывается на ходу (см. «Медленное соединение» в README).

